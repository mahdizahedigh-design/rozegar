export function getOccasionsForDate(jm: number, jd: number): Occasion[] {
  return ALL_OCCASIONS.filter((o) => o.jm === jm && o.jd === jd);
}

export function getMonthOccasions(jm: number): Occasion[] {
  return ALL_OCCASIONS.filter((o) => o.jm === jm);
}

export function getOccasionSummary(jm: number, jd: number): string | null {
  const occasions = getOccasionsForDate(jm, jd);
  if (occasions.length === 0) return null;
  return occasions.map((o) => o.name).join(' • ');
}
